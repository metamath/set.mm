  Mersenne primes
-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-.-

"In mathematics, a _Mersenne prime_ is a prime number that is one less than a
power of two.  That is, it is a prime number of the form M_n = 2^n-1 for some
integer n.  They are named after Marin Mersenne ...  If n is a composite number
then so is 2^n-1.  Therefore, an equivalent definition of the Mersenne primes
is that they are the prime numbers of the form M_p = 2^p-1 for some prime p.",
see Wikipedia "Mersenne prime", 16-Aug-2021,
~ https://en.wikipedia.org/wiki/Mersenne_prime . See also definition in
[ApostolNT] p. 4.

This means that if M_n = 2^n-1 is prime, than n must be prime, too, see
~ mersenne .  The reverse direction is not generally valid: If p is prime,
then M_p = 2^p-1 needs not be prime, e.g. M_11 = 2047 = 23 x 89, see
~ m11nprm .  This is an example of ~ sgprmdvdsmersenne , stating that if p
with p = 3 modulo 4 (here 11) and q=2p+1 (here 23) are prime, then q divides
M_p.

"In number theory, a prime number p is a _Sophie Germain prime_ if 2p+1 is also
prime.  The number 2p+1 associated with a Sophie Germain prime is called a
_safe prime_.", see Wikipedia "Safe and Sophie Germain primes", 21-Aug-2021,
~ https://en.wikipedia.org/wiki/Safe_and_Sophie_Germain_primes . Hence,
11 is a Sophie Germain prime and 2x11+1=23 is its associated safe prime.  By
~ sfprmdvdsmersenne , it is shown that if a safe prime q is congruent to 7
modulo 8, then it is a divisor of the Mersenne number with its matching Sophie
Germain prime as exponent.

The main result of this section, however, is the formal proof of a theorem of
S. Ligh and L. Neal in "A note on Mersenne numbers", see ~ lighneal .

